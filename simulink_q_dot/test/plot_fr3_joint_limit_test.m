    fprintf( ...
        ['忽略JointState启动阶段的%d个无效采样点，' ...
         '原始时间约为%.3f s。\n'], ...
        firstValidJointIndex-1, ...
        timeQ(firstValidJointIndex));
end

qData = qData(firstValidJointIndex:end,:);
timeQ = timeQ(firstValidJointIndex:end);
timeQ = timeQ - timeQ(1);

%% =========================================================
%% 6. 清理NaN和Inf
%% =========================================================

[timeQ,qData] = removeNonfiniteRows( ...
    timeQ, ...
    qData, ...
    'joint position');

[timeV,vData] = removeNonfiniteRows( ...
    timeV, ...
    vData, ...
    'command velocity');

[timeA,aData] = removeNonfiniteRows( ...
    timeA, ...
    aData, ...
    'command acceleration');

%% =========================================================
%% 7. 关节位置指标
%% =========================================================


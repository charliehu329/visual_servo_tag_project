function [position_valid,velocity_valid,position_C,relative_velocity_C, ...
    visual_source_stamp,visual_source_stamp_valid] = fcn( ...
    target_data,target_count,target_age,target_timeout_sec)
%#codegen
% 解析并校验带图像源时间戳的八元素视觉消息。
[position_valid_raw,velocity_valid_raw,position_C,relative_velocity_C, ...
    visual_source_stamp,visual_source_stamp_valid_raw]= ...
    parse_target_measurement(target_data,target_count,target_age, ...
    target_timeout_sec);
position_valid=double(position_valid_raw);
velocity_valid=double(velocity_valid_raw);
visual_source_stamp_valid=double(visual_source_stamp_valid_raw);
end

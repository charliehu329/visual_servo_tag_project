function codeText = jointGuardFunctionCode()

codeText = strjoin([ ...
"function [qdot_command,velocity_scale,acceleration_scale,position_scale,guard_valid] = fcn( ...", ...
"    qdot_raw,q,safe_valid,control_active,solver_valid,guard_parameters, ...", ...
"    qdot_limit,qddot_limit,q_min,q_max)", ...
"%#codegen", ...
"% 全系统唯一的最终关节命令处理：", ...
"% 一阶低通 -> 整体速度缩放 -> 整体加速度缩放 -> 软位置边界。", ...
"% 所有缩放均对 7 维向量同比例处理，不逐关节裁剪控制方向。", ...
"", ...
"persistent filtered_velocity previous_command initialized", ...
"if isempty(initialized)", ...
"    filtered_velocity=zeros(7,1); previous_command=zeros(7,1);", ...
"    initialized=true;", ...
"end", ...
"", ...
"qdot_command=zeros(7,1); velocity_scale=0.0; acceleration_scale=0.0;", ...
"position_scale=0.0; guard_valid=false;", ...
"qdot_raw=reshape(qdot_raw,7,1); q=reshape(q,7,1);", ...
"qdot_limit=reshape(qdot_limit,7,1);", ...
"qddot_limit=reshape(qddot_limit,7,1);", ...
"q_min=reshape(q_min,7,1); q_max=reshape(q_max,7,1);", ...
"", ...
"input_ok=numel(guard_parameters)>=3 && ...", ...
"    all(isfinite(qdot_raw(:))) && all(isfinite(q(:))) && ...", ...
"    all(isfinite(qdot_limit(:))) && all(qdot_limit>0.0) && ...", ...
"    all(isfinite(qddot_limit(:))) && all(qddot_limit>0.0) && ...", ...
"    all(isfinite(q_min(:))) && all(isfinite(q_max(:))) && ...", ...
"    all(q_max>q_min) && all(isfinite(guard_parameters(1:3)));", ...
"if ~input_ok", ...
"    filtered_velocity=zeros(7,1); previous_command=zeros(7,1); return;", ...
"end", ...
"", ...
"Ts=guard_parameters(1); filter_tau=guard_parameters(2);", ...
"soft_margin=guard_parameters(3);", ...
"parameter_ok=Ts>0.0 && filter_tau>=0.0 && soft_margin>0.0;", ...
"if ~parameter_ok", ...
"    filtered_velocity=zeros(7,1); previous_command=zeros(7,1); return;", ...
"end", ...
"", ...
"target_velocity=zeros(7,1);", ...
"% 使能或数据失效时把目标速度置零，但保留同一低通与加速度限制缓降。", ...
"if safe_valid && control_active && solver_valid", ...
"    target_velocity=qdot_raw;", ...
"end", ...
"", ...
"% 唯一一次命令低通滤波。tau=0 表示关闭。", ...
"alpha=Ts/(filter_tau+Ts);", ...
"filtered_velocity=filtered_velocity+alpha*(target_velocity-filtered_velocity);", ...
"", ...
"% 整体速度缩放：任一关节达到软件限值时，7 维方向同比例保留。", ...
"maximum_velocity_ratio=max(abs(filtered_velocity)./qdot_limit);", ...
"velocity_scale=1.0/max(1.0,maximum_velocity_ratio);", ...
"velocity_limited=filtered_velocity*velocity_scale;", ...
"", ...
"% 在建议矩形位置工作区的边缘做整体降速。", ...
"position_scale=1.0;", ...
"for joint_index=1:7", ...
"    if velocity_limited(joint_index)>0.0", ...
"        distance_to_limit=q_max(joint_index)-q(joint_index);", ...
"        local_scale=min(max(distance_to_limit/soft_margin,0.0),1.0);", ...
"        position_scale=min(position_scale,local_scale);", ...
"    elseif velocity_limited(joint_index)<0.0", ...
"        distance_to_limit=q(joint_index)-q_min(joint_index);", ...
"        local_scale=min(max(distance_to_limit/soft_margin,0.0),1.0);", ...
"        position_scale=min(position_scale,local_scale);", ...
"    end", ...
"end", ...
"velocity_limited=velocity_limited*position_scale;", ...
"", ...
"% 整体加速度缩放：限制本周期 7 维速度变化，保持变化方向。", ...
"delta_velocity=velocity_limited-previous_command;", ...
"maximum_acceleration_ratio=max(abs(delta_velocity)./(qddot_limit*Ts));", ...
"acceleration_scale=1.0/max(1.0,maximum_acceleration_ratio);", ...
"qdot_command=previous_command+delta_velocity*acceleration_scale;", ...
"", ...
"% 若已经到达软件位置边界，安全边界优先于平滑性，禁止继续向外。", ...
"emergency_position_scale=1.0;", ...
"for joint_index=1:7", ...
"    moving_outward=(q(joint_index)>=q_max(joint_index) && qdot_command(joint_index)>0.0) || ...", ...
"        (q(joint_index)<=q_min(joint_index) && qdot_command(joint_index)<0.0);", ...
"    if moving_outward, emergency_position_scale=0.0; end", ...
"end", ...
"qdot_command=qdot_command*emergency_position_scale;", ...
"position_scale=position_scale*emergency_position_scale;", ...
"", ...
"guard_valid=all(isfinite(qdot_command(:)));", ...
"if guard_valid", ...
"    previous_command=qdot_command;", ...
"else", ...
"    qdot_command=zeros(7,1); filtered_velocity=zeros(7,1);", ...
"    previous_command=zeros(7,1); velocity_scale=0.0;", ...
"    acceleration_scale=0.0; position_scale=0.0;", ...
"end", ...
"end" ...
], newline);

end



function outputModelFile = build_single_camera_joint_velocity_direct(sourceModelFile)
%BUILD_SINGLE_CAMERA_JOINT_VELOCITY_DIRECT
% 以现有 single_camera_xy_tracking_isnew 模型为底稿，生成一个由
% Simulink 直接向 JointVelocityExampleController 发布 7 维关节速度的模型。
%
% 新控制链路：
%   原消息接收/校验与原四状态匀速 KF 使能逻辑
%       -> 完整点特征视觉雅可比 (2x7)
%       -> 阻尼冗余关节速度求解
%       -> 零空间关节中心、软限位和深度安全区任务
%       -> 最底层唯一一次关节速度低通、整体速度缩放和整体加速度限制
%       -> /joint_velocity_example_controller/commands
%
% 说明：
% 1. 不修改源模型，输出 single_camera_joint_velocity_direct.slx。
% 2. 不再使用 Python 速度映射/转发节点。
% 3. 原 KF 中的前馈低通、XY 速度限幅和 XY 加速度限幅参数已删除。
% 4. 原 safe_valid、target_visible、target_is_new、P/FF/controller_enable
%    使能关系保持不变；仅把其二维相机平移请求交给完整视觉雅可比求解。
% 5. JointState 按 name 重排为 fr3_joint1...fr3_joint7；名称缺失、重复或
%    position/velocity 对应索引不存在时，本次关节反馈判为无效。
% 6. 第一次只能在仿真或 dry-run 下检查方向、坐标系和 Topic，不能直接高速上机。
%
% 用法：
%   build_single_camera_joint_velocity_direct( ...
%       'single_camera_xy_tracking_isnew.slx');
%
% 如果不传文件名，脚本会在当前文件夹、upload 子文件夹和当前工作目录
% 中查找 single_camera_xy_tracking_isnew*.slx。

if nargin < 1 || isempty(sourceModelFile)
    sourceModelFile = findSourceModel();
end

sourceModelFile = char(sourceModelFile);
assert(isfile(sourceModelFile), ...
    '找不到源模型：%s', sourceModelFile);

buildFolder = fileparts(mfilename('fullpath'));
outputModel = 'single_camera_joint_velocity_direct';
outputModelFile = fullfile(buildFolder, [outputModel '.slx']);

% 上传后的文件名可能带“(1)”，不是合法 Simulink 模型名。
% 先复制到一个合法的临时模型名，再另存为输出模型。
temporaryModelFile = [tempname(tempdir) '.slx'];
copyfile(sourceModelFile, temporaryModelFile, 'f');
[~, temporaryModel] = fileparts(temporaryModelFile);

cleanupObject = onCleanup(@()cleanupTemporaryModel( ...
    temporaryModel, temporaryModelFile)); %#ok<NASGU>

closeModelIfLoaded(outputModel);
if isfile(outputModelFile)
    delete(outputModelFile);
end

load_system(temporaryModelFile);
save_system(temporaryModel, outputModelFile);
close_system(temporaryModel, 0);
load_system(outputModelFile);

%% 1. 删除旧的 Python 中间链路和实验记录模块

deleteBlockIfPresent([outputModel '/Camera Velocity Publisher']);
deleteBlockIfPresent([outputModel '/Watchdog and Safety']);
deleteBlockIfPresent([outputModel '/velocity_command Subscriber']);
deleteBlockIfPresent([outputModel '/Logging']);
deleteBlockIfPresent([outputModel '/Scope']);

workspaceBlocks = find_system( ...
    outputModel, ...
    'SearchDepth', 1, ...
    'BlockType', 'ToWorkspace');
for blockIndex = 1:numel(workspaceBlocks)
    delete_block(workspaceBlocks{blockIndex});
end

%% 2. 按 JointState.name 重排 FR3 七个关节

jointStateSubscriber = [outputModel '/Joint State ROS2 Subscriber'];
configureJointStateNameReordering(jointStateSubscriber);

%% 3. 重构运动学反馈：输出完整相机 Jacobian [v;omega]

oldKinematics = [outputModel '/v_measured Subscribe'];
set_param(oldKinematics, 'Name', 'Kinematics Feedback');
kinematics = [outputModel '/Kinematics Feedback'];

set_param([kinematics '/Get Jacobian'], ...
    'RigidBodyTree', 'fr3_camera_robot', ...
    'EndEffector', 'camera_link');

set_param([kinematics '/Get Transform'], ...
    'RigidBodyTree', 'fr3_camera_robot', ...
    'SourceBody', 'camera_link', ...
    'TargetBody', 'base');

kinematicsFunction = [kinematics '/MATLAB Function'];
setMatlabFunctionScript(kinematicsFunction, kinematicsFunctionCode());

set_param([kinematics '/v_camera_measured'], ...
    'Name', 'camera_twist_measured');
set_param([kinematics '/feedback_valid'], ...
    'Name', 'kinematics_valid');

add_block('simulink/Sinks/Out1', ...
    [kinematics '/J_camera'], ...
    'Port', '4', ...
    'Position', [1160 405 1190 425]);

connectPorts( ...
    kinematicsFunction, 4, ...
    [kinematics '/J_camera'], 1);

%% 4. 保留原 KF/使能逻辑，删除旧命令滤波和限幅接口

oldEstimator = [outputModel '/Planar Target EKF'];
set_param(oldEstimator, 'Name', 'Planar Target KF and Task Command');
estimator = [outputModel '/Planar Target KF and Task Command'];

% 删除原二维命令链路遗留的三个参数。新的关节命令只在最终 Guard 中
% 进行一次低通、速度限制和加速度限制。
deleteConstantBlocksByValue(estimator, { ...
    'v_xy_max', ...
    'a_xy_max', ...
    'ff_filter_tau'});

parameterVector = find_system( ...
    estimator, ...
    'SearchDepth', 1, ...
    'BlockType', 'Concatenate');
assert(numel(parameterVector) == 1, ...
    '无法唯一定位 KF 参数向量拼接块。');
set_param(parameterVector{1}, 'NumInputs', '10');

deleteAnnotationsInSubsystem(estimator);

set_param([estimator '/EKF and Controller Core'], ...
    'Name', 'KF and Task Command Core');
estimatorFunction = [estimator '/KF and Task Command Core'];
setMatlabFunctionScript(estimatorFunction, estimatorFunctionCode());

% MATLAB Function 块来自旧模型。仅替换 Script 不会自动清除
% Stateflow 中保存的固定输入尺寸；旧 parameters 仍可能保持为 [12 1]。
% 新参数向量已经删除三项旧命令参数，因此必须显式同步为 [10 1]。
setMatlabFunctionInputSize(estimatorFunction, 'parameters', [10 1]);

% 删除 ff_filter_tau 后，z 成为 MATLAB Function 的第 13 个输入。
% 显式重连，避免源模型旧端口号残留。
reconnectPorts([estimator '/z'], 1, estimatorFunction, 13);

% 外层子系统保留原端口编号，避免破坏已有诊断接口；只更新旧名称。
set_param([estimator '/v_norm_limited'], 'Name', 'v_task_raw');
set_param([estimator '/saturation_active'], 'Name', 'control_active');

%% 5. 新增完整视觉雅可比和冗余关节速度求解器

solverBlock = [outputModel '/Redundant Visual Velocity Solver'];
add_block('simulink/User-Defined Functions/MATLAB Function', ...
    solverBlock, ...
    'Position', [1900 520 2220 950]);
setMatlabFunctionScript(solverBlock, redundantSolverFunctionCode());

solverParameters = [outputModel '/Solver Parameters'];
add_block('simulink/Sources/Constant', ...
    solverParameters, ...
    'Value', [ ...
    '[visual_damping_min;visual_damping_max;' ...
    'singularity_sigma_stop;singularity_sigma_warn;' ...
    'nullspace_posture_gain;depth_safe_min;depth_safe_max;' ...
    'depth_safety_gain;visual_min_depth]'], ...
    'Position', [1550 1040 1780 1080]);

nominalConfiguration = [outputModel '/Nominal Joint Configuration'];
add_block('simulink/Sources/Constant', ...
    nominalConfiguration, ...
    'Value', 'joint_nominal_configuration', ...
    'Position', [1550 1100 1780 1140]);

jointMinimum = [outputModel '/Joint Minimum'];
add_block('simulink/Sources/Constant', ...
    jointMinimum, ...
    'Value', 'joint_position_min', ...
    'Position', [1550 1160 1780 1200]);

jointMaximum = [outputModel '/Joint Maximum'];
add_block('simulink/Sources/Constant', ...
    jointMaximum, ...
    'Value', 'joint_position_max', ...
    'Position', [1550 1220 1780 1260]);

% 从 Outport 块读取真实端口号，避免再次把信号按函数输出顺序误接。
estimatorControllerOkPort = getOutportNumber( ...
    [estimator '/controller_ok']);
estimatorTaskVelocityPort = getOutportNumber( ...
    [estimator '/v_task_raw']);
estimatorControlActivePort = getOutportNumber( ...
    [estimator '/control_active']);

% Solver 输入顺序由 redundantSolverFunctionCode 的函数签名确定。
connectPorts(estimator, estimatorTaskVelocityPort, solverBlock, 1);
connectPorts([outputModel '/Normalized Image Coordinates'], 1, solverBlock, 2);
connectPorts([outputModel '/Message Validation'], 7, solverBlock, 3); % z
connectPorts(kinematics, 4, solverBlock, 4);                % J_camera
connectPorts([outputModel '/Message Validation'], 4, solverBlock, 5); % q
connectPorts([outputModel '/Message Validation'], 1, solverBlock, 6); % safe_valid
connectPorts(estimator, estimatorControlActivePort, solverBlock, 7);
connectPorts(estimator, estimatorControllerOkPort, solverBlock, 8);
connectPorts(kinematics, 2, solverBlock, 9);                % kinematics_valid
connectPorts(solverParameters, 1, solverBlock, 10);
connectPorts(nominalConfiguration, 1, solverBlock, 11);
connectPorts(jointMinimum, 1, solverBlock, 12);
connectPorts(jointMaximum, 1, solverBlock, 13);

%% 6. 新增唯一的最底层关节命令滤波/速度/加速度/限位保护

guardBlock = [outputModel '/Final Joint Command Guard'];
add_block('simulink/User-Defined Functions/MATLAB Function', ...
    guardBlock, ...
    'Position', [2350 540 2660 950]);
setMatlabFunctionScript(guardBlock, jointGuardFunctionCode());

guardParameters = [outputModel '/Guard Parameters'];
add_block('simulink/Sources/Constant', ...
    guardParameters, ...
    'Value', '[Ts;joint_command_filter_tau;joint_soft_margin]', ...
    'Position', [2310 1035 2540 1075]);

jointVelocityLimit = [outputModel '/Joint Velocity Limit'];
add_block('simulink/Sources/Constant', ...
    jointVelocityLimit, ...
    'Value', 'joint_velocity_limit', ...
    'Position', [2310 1095 2540 1135]);

jointAccelerationLimit = [outputModel '/Joint Acceleration Limit'];
add_block('simulink/Sources/Constant', ...
    jointAccelerationLimit, ...
    'Value', 'joint_acceleration_limit', ...
    'Position', [2310 1155 2540 1195]);

connectPorts(solverBlock, 1, guardBlock, 1);                % qdot_raw
connectPorts([outputModel '/Message Validation'], 4, guardBlock, 2);
connectPorts([outputModel '/Message Validation'], 1, guardBlock, 3);
connectPorts(estimator, estimatorControlActivePort, guardBlock, 4);
connectPorts(solverBlock, 5, guardBlock, 5);               % solver_valid
connectPorts(guardParameters, 1, guardBlock, 6);
connectPorts(jointVelocityLimit, 1, guardBlock, 7);
connectPorts(jointAccelerationLimit, 1, guardBlock, 8);
connectPorts(jointMinimum, 1, guardBlock, 9);
connectPorts(jointMaximum, 1, guardBlock, 10);

%% 7. Simulink 直接发布 7 维关节角速度

publisher = [outputModel '/Joint Velocity Publisher'];
addJointVelocityPublisher( ...
    publisher, ...
    '/joint_velocity_example_controller/commands');
connectPorts(guardBlock, 1, publisher, 1);

%% 8. 参数、显示与保存

appendNewInitializationParameters(outputModel);

set_param(outputModel, ...
    'SolverType', 'Fixed-step', ...
    'FixedStep', 'Ts', ...
    'StopTime', 'inf');

add_block('simulink/Sinks/Display', ...
    [outputModel '/qdot command monitor'], ...
    'Position', [2920 610 3060 700]);
connectPorts(guardBlock, 1, ...
    [outputModel '/qdot command monitor'], 1);

set_param(outputModel, 'SimulationCommand', 'Update');

Simulink.BlockDiagram.arrangeSystem(outputModel);

save_system(outputModel, outputModelFile);
open_system(outputModel);

fprintf('\n已生成模型：\n  %s\n', outputModelFile);
fprintf('最终发布 Topic：\n  /joint_velocity_example_controller/commands\n');
fprintf(['首次测试：保持 controller 未激活或使用 dry-run，先检查 7 维长度、' ...
    '左右/上下方向、sigma_min 和零命令。\n\n']);

end


function sourceModelFile = findSourceModel()

buildFolder = fileparts(mfilename('fullpath'));
searchFolders = { ...
    buildFolder, ...
    fullfile(buildFolder, 'upload'), ...
    pwd};

sourceModelFile = '';
for folderIndex = 1:numel(searchFolders)
    if ~isfolder(searchFolders{folderIndex})
        continue;
    end

    candidates = dir(fullfile( ...
        searchFolders{folderIndex}, ...
        'single_camera_xy_tracking_isnew*.slx'));

    if ~isempty(candidates)
        sourceModelFile = fullfile( ...
            candidates(1).folder, ...
            candidates(1).name);
        break;
    end
end

assert(~isempty(sourceModelFile), ...
    ['没有找到 single_camera_xy_tracking_isnew*.slx。' ...
     '请把源模型路径作为输入传给 build 函数。']);

end


function cleanupTemporaryModel(temporaryModel, temporaryModelFile)

closeModelIfLoaded(temporaryModel);
if isfile(temporaryModelFile)
    delete(temporaryModelFile);
end

end


function closeModelIfLoaded(modelName)

if bdIsLoaded(modelName)
    close_system(modelName, 0);
end

end


function deleteBlockIfPresent(blockPath)

if getSimulinkBlockHandle(blockPath) ~= -1
    delete_block(blockPath);
end

end


function deleteConstantBlocksByValue(subsystemPath, valuesToDelete)

constantBlocks = find_system( ...
    subsystemPath, ...
    'SearchDepth', 1, ...
    'BlockType', 'Constant');

for blockIndex = 1:numel(constantBlocks)
    blockValue = strtrim(get_param(constantBlocks{blockIndex}, 'Value'));
    if any(strcmp(blockValue, valuesToDelete))
        delete_block(constantBlocks{blockIndex});
    end
end

end


function deleteAnnotationsInSubsystem(subsystemPath)

annotationHandles = find_system( ...
    subsystemPath, ...
    'SearchDepth', 1, ...
    'FindAll', 'on', ...
    'Type', 'annotation');

for annotationIndex = 1:numel(annotationHandles)
    annotationObject = get_param( ...
        annotationHandles(annotationIndex), ...
        'Object');
    delete(annotationObject);
end

end


function setMatlabFunctionScript(blockPath, codeText)

stateflowRoot = sfroot;
chartObject = stateflowRoot.find( ...
    '-isa', 'Stateflow.EMChart', ...
    'Path', blockPath);

assert(numel(chartObject) == 1, ...
    '无法唯一定位 MATLAB Function：%s', blockPath);

chartObject.Script = char(codeText);

end


function setMatlabFunctionInputSize(blockPath, inputName, inputSize)

stateflowRoot = sfroot;
chartObject = stateflowRoot.find( ...
    '-isa', 'Stateflow.EMChart', ...
    'Path', blockPath);

assert(numel(chartObject) == 1, ...
    '无法唯一定位 MATLAB Function：%s', blockPath);

dataObjects = chartObject.Inputs;
nameMatches = false(size(dataObjects));
for dataIndex = 1:numel(dataObjects)
    nameMatches(dataIndex) = strcmp(dataObjects(dataIndex).Name, inputName);
end
inputData = dataObjects(nameMatches);

assert(numel(inputData) == 1, ...
    '无法唯一定位 MATLAB Function 输入 %s：%s', inputName, blockPath);
assert(isnumeric(inputSize) && numel(inputSize) == 2 && ...
    all(isfinite(inputSize)) && all(inputSize >= 1) && ...
    all(inputSize == floor(inputSize)), ...
    'MATLAB Function 输入尺寸无效：%s', inputName);

inputData.Props.Array.Size = sprintf('[%d %d]', inputSize(1), inputSize(2));

end


function reconnectPorts(sourceBlock, sourcePort, destinationBlock, destinationPort)

sourceHandles = get_param(sourceBlock, 'PortHandles');
assert(numel(sourceHandles.Outport) >= sourcePort, ...
    '源块端口不存在：%s/%d', sourceBlock, sourcePort);

oldLine = get_param(sourceHandles.Outport(sourcePort), 'Line');
if oldLine ~= -1
    delete_line(oldLine);
end

connectPorts(sourceBlock, sourcePort, destinationBlock, destinationPort);

end


function configureJointStateNameReordering(subsystemPath)

selector = [subsystemPath '/Select Joint Arrays'];
assert(getSimulinkBlockHandle(selector) ~= -1, ...
    '找不到 JointState Bus Selector：%s', selector);

set_param(selector, 'Name', 'Select Joint State Fields');
selector = [subsystemPath '/Select Joint State Fields'];
set_param(selector, ...
    'OutputSignals', [ ...
    'name,name_SL_Info,' ...
    'position,position_SL_Info,' ...
    'velocity,velocity_SL_Info']);

unpackFunction = [subsystemPath '/Unpack'];
setMatlabFunctionScript(unpackFunction, jointStateUnpackFunctionCode());

% 替换函数签名后，清除旧的四输入连线并按新八输入接口显式重连。
deleteAllInputLines(unpackFunction);

subscribe = [subsystemPath '/Subscribe'];
clockBlock = [subsystemPath '/Clock'];

connectPorts(selector, 1, unpackFunction, 1);  % name
connectPorts(selector, 2, unpackFunction, 2);  % name_SL_Info
connectPorts(selector, 3, unpackFunction, 3);  % position
connectPorts(selector, 4, unpackFunction, 4);  % position_SL_Info
connectPorts(selector, 5, unpackFunction, 5);  % velocity
connectPorts(selector, 6, unpackFunction, 6);  % velocity_SL_Info
connectPorts(subscribe, 1, unpackFunction, 7); % IsNew
connectPorts(clockBlock, 1, unpackFunction, 8); % current time

end


function deleteAllInputLines(blockPath)

portHandles = get_param(blockPath, 'PortHandles');
for portIndex = 1:numel(portHandles.Inport)
    lineHandle = get_param(portHandles.Inport(portIndex), 'Line');
    if lineHandle ~= -1
        delete_line(lineHandle);
    end
end

end


function portNumber = getOutportNumber(outportBlock)

assert(getSimulinkBlockHandle(outportBlock) ~= -1, ...
    '找不到 Outport 块：%s', outportBlock);

portNumber = str2double(get_param(outportBlock, 'Port'));
assert(isfinite(portNumber) && portNumber >= 1 && ...
    portNumber == floor(portNumber), ...
    'Outport 端口号无效：%s', outportBlock);

end


function connectPorts(sourceBlock, sourcePort, destinationBlock, destinationPort)

sourceHandles = get_param(sourceBlock, 'PortHandles');
destinationHandles = get_param(destinationBlock, 'PortHandles');

assert(numel(sourceHandles.Outport) >= sourcePort, ...
    '源块端口不存在：%s/%d', sourceBlock, sourcePort);
assert(numel(destinationHandles.Inport) >= destinationPort, ...
    '目标块端口不存在：%s/%d', destinationBlock, destinationPort);

sourceParent = get_param(sourceBlock, 'Parent');
destinationParent = get_param(destinationBlock, 'Parent');
assert(strcmp(sourceParent, destinationParent), ...
    '连线两端不在同一层：%s -> %s', sourceBlock, destinationBlock);

add_line( ...
    sourceParent, ...
    sourceHandles.Outport(sourcePort), ...
    destinationHandles.Inport(destinationPort), ...
    'autorouting', 'on');

end


function addJointVelocityPublisher(subsystemPath, topicName)

add_block('simulink/Ports & Subsystems/Subsystem', ...
    subsystemPath, ...
    'Position', [2760 540 2930 720]);

deleteBlockIfPresent([subsystemPath '/In1']);
deleteBlockIfPresent([subsystemPath '/Out1']);

inport = [subsystemPath '/qdot_command'];
add_block('simulink/Sources/In1', ...
    inport, ...
    'Position', [30 110 60 130]);

blankMessage = [subsystemPath '/Blank Message'];
add_block('ros2lib/Blank Message', ...
    blankMessage, ...
    'Position', [30 25 155 65]);
set_param(blankMessage, ...
    'messageClass', 'Message', ...
    'entityType', 'std_msgs/Float64MultiArray', ...
    'messageType', 'std_msgs/Float64MultiArray', ...
    'SampleTime', 'Ts');

packFunction = [subsystemPath '/Pack Seven Joint Velocities'];
add_block('simulink/User-Defined Functions/MATLAB Function', ...
    packFunction, ...
    'Position', [110 95 300 155]);
setMatlabFunctionScript(packFunction, publisherPackFunctionCode());

busAssignment = [subsystemPath '/Assign Data'];
add_block('simulink/Signal Routing/Bus Assignment', ...
    busAssignment, ...
    'AssignedSignals', ...
    'data,data_SL_Info.CurrentLength,data_SL_Info.ReceivedLength', ...
    'Position', [350 30 485 135]);

publishBlock = [subsystemPath '/Publish'];
add_block('ros2lib/Publish', ...
    publishBlock, ...
    'Position', [550 50 690 115]);
set_param(publishBlock, ...
    'topicSource', 'Specify your own', ...
    'topic', topicName, ...
    'messageType', 'std_msgs/Float64MultiArray', ...
    'QOSHistory', 'Keep last', ...
    'QOSDepth', '1', ...
    'QOSReliability', 'Reliable', ...
    'QOSDurability', 'Volatile');

connectPorts(inport, 1, packFunction, 1);
connectPorts(blankMessage, 1, busAssignment, 1);
connectPorts(packFunction, 1, busAssignment, 2);
connectPorts(packFunction, 2, busAssignment, 3);
connectPorts(packFunction, 3, busAssignment, 4);
connectPorts(busAssignment, 1, publishBlock, 1);

end


function appendNewInitializationParameters(modelName)

oldInitialization = get_param(modelName, 'InitFcn');

newInitialization = strjoin([ ...
    "% Direct joint-velocity refactor defaults", ...
    "if ~exist('visual_damping_min','var'), visual_damping_min = 0.015; end", ...
    "if ~exist('visual_damping_max','var'), visual_damping_max = 0.20; end", ...
    "if ~exist('singularity_sigma_stop','var'), singularity_sigma_stop = 0.025; end", ...
    "if ~exist('singularity_sigma_warn','var'), singularity_sigma_warn = 0.080; end", ...
    "if ~exist('nullspace_posture_gain','var'), nullspace_posture_gain = 0.08; end", ...
    "if ~exist('depth_safe_min','var'), depth_safe_min = 0.30; end", ...
    "if ~exist('depth_safe_max','var'), depth_safe_max = 0.80; end", ...
    "if ~exist('depth_safety_gain','var'), depth_safety_gain = 0.50; end", ...
    "if ~exist('visual_min_depth','var'), visual_min_depth = 0.10; end", ...
    "if ~exist('joint_command_filter_tau','var'), joint_command_filter_tau = 0.040; end", ...
    "if ~exist('joint_soft_margin','var'), joint_soft_margin = 0.15; end", ...
    "if ~exist('joint_nominal_configuration','var'), joint_nominal_configuration = [0;-pi/4;0;-3*pi/4;0;pi/2;pi/4]; end", ...
    "% Franka 官方建议的矩形位置工作区，而不是硬件绝对边界。", ...
    "if ~exist('joint_position_min','var'), joint_position_min = [-2.3476;-1.5454;-2.4937;-2.7714;-2.5100;0.7773;-2.7045]; end", ...
    "if ~exist('joint_position_max','var'), joint_position_max = [2.3476;1.5454;2.4937;-0.4226;2.5100;4.2841;2.7045]; end", ...
    "% 初次真机验证使用保守的软件速度/加速度，不等同于 FR3 硬件极限。", ...
    "if ~exist('joint_velocity_limit','var'), joint_velocity_limit = [0.50;0.50;0.50;0.50;0.75;0.75;0.75]; end", ...
    "if ~exist('joint_acceleration_limit','var'), joint_acceleration_limit = 1.50*ones(7,1); end" ...
    ], newline);

set_param(modelName, ...
    'InitFcn', sprintf('%s\n\n%s', oldInitialization, newInitialization));

end


function codeText = jointStateUnpackFunctionCode()

codeText = strjoin([ ...
"function [joint_position,joint_count,joint_velocity,joint_age] = fcn( ...", ...
"    name,name_info,position,position_info,velocity,velocity_info,is_new,t)", ...
"%#codegen", ...
"% ROS JointState 的 name、position、velocity 使用相同索引。", ...
"% 仅当 fr3_joint1...fr3_joint7 均唯一存在且数组索引完整时才更新输出。", ...
"", ...
"persistent last_q last_dq last_count last_time", ...
"if isempty(last_count)", ...
"    last_q=zeros(7,1); last_dq=zeros(7,1);", ...
"    last_count=0.0; last_time=-1.0e6;", ...
"end", ...
"", ...
"if is_new", ...
"    last_q=zeros(7,1); last_dq=zeros(7,1);", ...

"L_depth=[0 0 -1.0 -Z*y Z*x 0];", ...
"J_depth=L_depth*J_camera;", ...
"J_depth_null=J_depth*N_image;", ...
"depth_denominator=J_depth_null*J_depth_null'+damping_used*damping_used;", ...
"qdot_depth=zeros(7,1);", ...
"if depth_rate_command~=0.0 && isfinite(depth_denominator) && depth_denominator>1e-12", ...
"    qdot_depth=N_image*J_depth'*(depth_rate_command/depth_denominator);", ...
"end", ...
"", ...
"% 奇异度缩放作用于主任务、零空间姿态和深度任务的总和。", ...
"% sigma_min<=sigma_stop 时三类运动均平滑降为零。", ...
"qdot_raw=singularity_scale*(qdot_task+qdot_null+qdot_depth);", ...
"solver_valid=all(isfinite(qdot_raw(:)));", ...
"if ~solver_valid, qdot_raw=zeros(7,1); end", ...

    else
        titleColor = [0.10 0.50 0.10];
        stateText = 'CENTER REGION';
    end

    title( ...
        ax, ...
        sprintf( ...
            ['Joint %d | %s | min margin %.4f rad | ' ...
             'max usage %.1f%%'], ...
            jointIndex, ...
            stateText, ...
            minimumMargin(jointIndex), ...
            maximumUsagePercent(jointIndex)), ...
        'Color',titleColor);

    if jointIndex == 1
        legend( ...
            ax, ...
            { ...
                'q', ...
                'Lower hard limit', ...
                'Upper hard limit', ...
                '60% lower', ...
                '60% upper', ...
                'Center' ...
            }, ...
            'Location','best');
    end
end


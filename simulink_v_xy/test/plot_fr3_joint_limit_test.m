%% plot_fr3_joint_limit_test.m
% FR3关节位置、命令速度、命令加速度综合测试脚本
%
% 自动读取：
%   log_joint_position          7维关节位置，rad
%   log_command_velocity        7维最终命令速度，rad/s
%   log_command_acceleration    7维命令加速度，rad/s^2
%
% 输出3个Figure：
%   1. 关节位置 + URDF硬限位 + 中央60%回中边界
%   2. 关节命令速度 + 速度限幅
%   3. 关节命令加速度 + 加速度限幅
%
% 自动保存：
%   PNG、FIG和3份CSV指标文件
%
% 使用：
%   完成一次Simulink测试后运行：
%
%       plot_fr3_joint_limit_test
%
% 说明：
%   - 自动忽略收到第一条合法JointState之前的默认零值。
%   - 使用print优先保存PNG，避免Linux下exportgraphics偶发报错。

%% =========================================================
%% 1. 用户可调参数
%% =========================================================

% 与Mapper一致：中央60%范围内不启动回中。
centerFreeRatio = 0.80;

% 与velocity_command_node一致：
% 最终速度上限 = FR3官方速度上限 * maxVelocityScale
maxVelocityScale = 0.40;

% 与velocity_command_node一致，单位rad/s^2。
maxJointAccelerations = [ ...
    0.50;
    0.50;
    0.50;
    0.50;
    0.50;
    0.50;
    0.50];

% 图片保存参数。
imageResolutionDpi = 200;
closeFiguresAfterSave = false;

% 输出目录。
outputFolder = fullfile( ...
    pwd, ...
    'test_results', ...
    'joint_command_monitor');

%% =========================================================
%% 2. FR3官方限制
%% =========================================================

% FR3官方关节速度上限，单位rad/s。
fr3MaxJointVelocitiesOfficial = [ ...
    2.62;
    2.62;
    2.62;
    2.62;
    5.26;
    4.18;
    5.26];

% FR3关节位置硬限位，来自fr3.urdf，单位rad。
qMin = [ ...
    -2.9007;
    -1.8361;
    -2.9007;
    -3.0770;
    -2.8763;
     0.4398;
    -3.0508];

qMax = [ ...
     2.9007;
     1.8361;
     2.9007;
    -0.1169;
     2.8763;
     4.6216;
     3.0508];

%% =========================================================
%% 3. 派生限制
%% =========================================================

qMid = 0.5*(qMin + qMax);
qHalfRange = 0.5*(qMax - qMin);

qCenterLower = ...
    qMid - centerFreeRatio*qHalfRange;

qCenterUpper = ...
    qMid + centerFreeRatio*qHalfRange;

commandVelocityLimit = ...
    fr3MaxJointVelocitiesOfficial*maxVelocityScale;

commandAccelerationLimit = ...
    maxJointAccelerations(:);

%% =========================================================
%% 4. 读取3类日志
%% =========================================================

jointSignal = findLoggedSignal( ...
    'log_joint_position');

velocitySignal = findLoggedSignal( ...
    'log_command_velocity');

accelerationSignal = findLoggedSignal( ...
    'log_command_acceleration');

if isempty(jointSignal)
    error([ ...
        '没有找到log_joint_position。' ...
        '请确认模型已记录7维关节位置。']);
end

if isempty(velocitySignal)
    error([ ...
        '没有找到log_command_velocity。' ...
        '请确认模型已记录7维最终命令速度。']);
end

if isempty(accelerationSignal)
    error([ ...
        '没有找到log_command_acceleration。' ...
        '请确认模型已记录7维命令加速度。']);
end

[timeQ,qData] = ...
    signalToTimeData(jointSignal);

[timeV,vData] = ...
    signalToTimeData(velocitySignal);

[timeA,aData] = ...
    signalToTimeData(accelerationSignal);

validateSevenJointData( ...
    qData, ...
    'log_joint_position');

validateSevenJointData( ...
    vData, ...
    'log_command_velocity');

validateSevenJointData( ...
    aData, ...
    'log_command_acceleration');

%% =========================================================
%% 5. 删除JointState启动阶段默认零值
%% =========================================================

% 第一条有效关节状态必须满足7个关节均位于URDF硬限位内。
insideAllJointLimits = all( ...
    qData >= qMin.' & ...
    qData <= qMax.', ...
    2);

firstValidJointIndex = find( ...
    insideAllJointLimits, ...
    1, ...
    'first');

if isempty(firstValidJointIndex)
    error( ...
        '整段日志中没有找到合法的7维关节位置。');
end

if firstValidJointIndex > 1
    fprintf( ...
        ['忽略JointState启动阶段的%d个无效采样点，' ...
         '原始时间约为%.3f s。\n'], ...
        firstValidJointIndex-1, ...
        timeQ(firstValidJointIndex));
end

qData = qData(firstValidJointIndex:end,:);
timeQ = timeQ(firstValidJointIndex:end);
timeQ = timeQ - timeQ(1);

%% =========================================================
%% 6. 清理NaN和Inf
%% =========================================================

[timeQ,qData] = removeNonfiniteRows( ...
    timeQ, ...
    qData, ...
    'joint position');

[timeV,vData] = removeNonfiniteRows( ...
    timeV, ...
    vData, ...
    'command velocity');

[timeA,aData] = removeNonfiniteRows( ...
    timeA, ...
    aData, ...
    'command acceleration');

%% =========================================================
%% 7. 关节位置指标
%% =========================================================

lowerMargin = qData - qMin.';
upperMargin = qMax.' - qData;

nearestMargin = min( ...
    lowerMargin, ...
    upperMargin);

% 0%=关节中点，100%=硬限位。
normalizedPosition = ...
    (qData - qMid.') ./ qHalfRange.';

limitUsagePercent = ...
    100*abs(normalizedPosition);

minimumMargin = min( ...
    nearestMargin, ...
    [], ...
    1, ...
    'omitnan');

maximumUsagePercent = max( ...
    limitUsagePercent, ...
    [], ...
    1, ...
    'omitnan');

finalPosition = qData(end,:);

%% =========================================================
%% 8. 命令速度指标
%% =========================================================

velocityUsagePercent = ...
    100*abs(vData) ./ commandVelocityLimit.';

maximumVelocityUsagePercent = max( ...
    velocityUsagePercent, ...
    [], ...
    1, ...
    'omitnan');

maximumVelocityAbs = max( ...
    abs(vData), ...
    [], ...
    1, ...
    'omitnan');

finalVelocity = vData(end,:);

%% =========================================================
%% 9. 命令加速度指标
%% =========================================================

accelerationUsagePercent = ...
    100*abs(aData) ./ commandAccelerationLimit.';

maximumAccelerationUsagePercent = max( ...
    accelerationUsagePercent, ...
    [], ...
    1, ...
    'omitnan');

maximumAccelerationAbs = max( ...
    abs(aData), ...
    [], ...
    1, ...
    'omitnan');

finalAcceleration = aData(end,:);

%% =========================================================
%% 10. 输出目录
%% =========================================================

if ~exist(outputFolder,'dir')
    mkdir(outputFolder);
end

timeStamp = char( ...
    datetime( ...
        'now', ...
        'Format','yyyyMMdd_HHmmss'));

fileBase = fullfile( ...
    outputFolder, ...
    ['fr3_joint_command_monitor_',timeStamp]);


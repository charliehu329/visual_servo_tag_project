        '60% lower boundary', ...
        'LabelHorizontalAlignment','left');

    yline( ...
        ax, ...
        qCenterUpper(jointIndex), ...
        'k:', ...
        '60% upper boundary', ...
        'LabelHorizontalAlignment','left');

    yline( ...
        ax, ...
        qMid(jointIndex), ...
        'b-.', ...
        'Center', ...
        'LabelHorizontalAlignment','left');

    grid(ax,'on');
    xlabel(ax,'Time (s)');
    ylabel(ax,sprintf('q_%d (rad)',jointIndex));

    positionPadding = ...
        0.08*(qMax(jointIndex)-qMin(jointIndex));

    ylim( ...
        ax, ...
        [ ...
            qMin(jointIndex)-positionPadding, ...
            qMax(jointIndex)+positionPadding ...
        ]);

    if maximumUsagePercent(jointIndex) >= 100
        titleColor = [0.85 0.10 0.10];
        stateText = 'HARD LIMIT EXCEEDED';


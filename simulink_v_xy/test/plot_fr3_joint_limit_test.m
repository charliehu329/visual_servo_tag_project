function signal = findLoggedSignal(signalName)

signal = [];
candidateOutputNames = {'out','simOut'};

for outputIndex = 1:numel(candidateOutputNames)
    outputName = candidateOutputNames{outputIndex};

    existsInBase = evalin( ...
        'base', ...
        sprintf( ...
            'exist(''%s'',''var'')', ...
            outputName));

    if ~existsInBase
        continue;
    end

    simulationOutput = evalin( ...
        'base', ...
        outputName);

    if ~isa( ...
            simulationOutput, ...
            'Simulink.SimulationOutput')
        continue;
    end

    outputNames = simulationOutput.who;

    if any(strcmp(outputNames,signalName))
        signal = simulationOutput.get(signalName);
        return;
    end

    if any(strcmp(outputNames,'logsout'))
        logsout = simulationOutput.get('logsout');

        if isa( ...
                logsout, ...
                'Simulink.SimulationData.Dataset')
            try
                element = logsout.getElement(signalName);
                signal = element.Values;
                return;
            catch
            end
        end
    end
end

existsDirectly = evalin( ...
    'base', ...
    sprintf( ...
        'exist(''%s'',''var'')', ...
        signalName));

if existsDirectly
    signal = evalin( ...
        'base', ...
        signalName);
end

end

function [time,data] = signalToTimeData(signal)

if isa( ...
        signal, ...
        'Simulink.SimulationData.Signal')
    signal = signal.Values;
end

if isa(signal,'timeseries')
    time = double(signal.Time(:));
    data = signal.Data;

elseif isstruct(signal) && ...
        isfield(signal,'time') && ...
        isfield(signal,'signals')
    time = double(signal.time(:));
    data = signal.signals.values;

elseif istimetable(signal)
    time = seconds( ...
        signal.Properties.RowTimes ...
        - signal.Properties.RowTimes(1));

    time = double(time(:));
    data = signal.Variables;

else
    error( ...
        '不支持的日志格式：%s', ...
        class(signal));
end

data = squeeze(data);

if isvector(data)
    data = data(:);

elseif size(data,1) == 7 && ...
        size(data,2) == numel(time)
    data = data.';

elseif size(data,1) ~= numel(time) && ...
        size(data,2) == numel(time)
    data = data.';

elseif size(data,1) ~= numel(time)
    data = reshape( ...
        data, ...
        numel(time), ...
        []);
end

data = double(data);

end

function validateSevenJointData(data,signalName)

if size(data,2) ~= 7
    error( ...
        '%s必须包含7列，当前尺寸为%s。', ...
        signalName, ...
        mat2str(size(data)));
end

end

function [time,data] = removeNonfiniteRows( ...
    time, ...
    data, ...
    signalDescription)

validRows = ...
    isfinite(time) & ...
    all(isfinite(data),2);

removedCount = sum(~validRows);

if removedCount > 0
    fprintf( ...
        '从%s中删除%d个NaN或Inf采样点。\n', ...
        signalDescription, ...
        removedCount);
end

time = time(validRows);
data = data(validRows,:);

if isempty(time)
    error( ...
        '%s清理后没有有效数据。', ...
        signalDescription);
end

end

function saveFigureSafely( ...
    figureHandle, ...
    fileBase, ...
    resolutionDpi)

if ~isgraphics(figureHandle,'figure')
    error( ...
        '准备保存%s时图窗句柄已经无效。', ...
        fileBase);
end

drawnow;

pngPath = [fileBase,'.png'];
figPath = [fileBase,'.fig'];

% Linux下优先使用print保存PNG。
try
    print( ...
        figureHandle, ...
        pngPath, ...
        '-dpng', ...
        sprintf('-r%d',resolutionDpi));

catch printError
    warning( ...
        ['print保存PNG失败，改用exportgraphics。\n' ...
         '原因：%s'], ...
        printError.message);

    if ~isgraphics(figureHandle,'figure')
        error( ...
            '回退保存时图窗已经无效：%s', ...
            fileBase);
    end

    exportgraphics( ...
        figureHandle, ...
        pngPath, ...
        'Resolution',resolutionDpi);
end

if isgraphics(figureHandle,'figure')
    savefig( ...
        figureHandle, ...
        figPath);
else
    warning( ...
        'PNG已保存，但FIG未保存，因为图窗已失效：%s', ...
        fileBase);
end

end

function closeValidFigure(figureHandle)

if isgraphics(figureHandle,'figure')
    close(figureHandle);
end

end